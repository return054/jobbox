/** 用于在 location 字符串中识别 district 的后缀 */
export const DISTRICT_SUFFIXES = [
  '新区', '开发区', '高新区', '经济区', '区', '县', '市',
] as const;

/** 取一个字符串是否以任一 district 后缀结尾 */
export function endsWithDistrictSuffix(s: string): boolean {
  return DISTRICT_SUFFIXES.some((suffix) => s.endsWith(suffix));
}
